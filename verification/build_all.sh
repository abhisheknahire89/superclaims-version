#!/usr/bin/env bash
# Rebuild every generated artifact and re-run every check, in dependency order.
# Usage (from pack root): bash verification/build_all.sh
set -euo pipefail
cd "$(dirname "$0")/.."
python3 verification/run_traces.py > /dev/null && echo "traces: OK (verification/trace-report.md)"
python3 verification/render_traces.py
python3 verification/build_worksheets.py
python3 verification/test_rules.py | tail -1 && echo "rule tests: OK"
python3 verification/test_invariants.py 3000
python3 verification/validate_contracts.py > /tmp/aw_contracts.json || { cat /tmp/aw_contracts.json; exit 1; }
python3 -c "import json; d=json.load(open('/tmp/aw_contracts.json')); print('contracts: passed=%d failed=%d' % (d['passed'], d['failed']))"
python3 verification/mutation_test_contracts.py > /tmp/aw_mut.txt && echo "mutation tests: $(grep -c '^caught' /tmp/aw_mut.txt) caught"
python3 verification/cost_model.py > /dev/null && echo "cost tables: OK (verification/cost-tables.md)"
python3 verification/build_ledger.py
python3 verification/build_wireframe.py
python3 verification/check_refs.py
# re-embed generated tables into the docs
python3 - <<'EOF'
import re, pathlib
def embed(doc, start_marker, end_marker, generated, header_note):
    p = pathlib.Path(doc); s = p.read_text()
    i = s.index(start_marker) + len(start_marker); j = s.index(end_marker, i)
    p.write_text(s[:i] + "\n\n" + header_note + "\n" + generated + "\n" + s[j:])
t = pathlib.Path("verification/trace-tables.md").read_text().split("\n", 1)[1].replace("### Output:", "#### Output:")
embed("06-rule-catalog.md", "### Generated trace tables", "## 8. Regulatory obligations",
      t, "_Generated by `verification/render_traces.py` from `fixtures/claims/*.output.json`. Money in ₹; amounts in the Deduction column are positive when they reduce the payable._")
c = pathlib.Path("verification/cost-tables.md").read_text().split("\n", 1)[1].replace("\n### ", "\n#### ")
embed("09-materials-and-costs.md", "### Generated cost tables", "## 6.", c, "_Generated by `verification/cost_model.py`; edit inputs there, not here._")
print("docs: generated sections re-embedded")
EOF
PGB="${PGBIN:-$(dirname "$(command -v initdb 2>/dev/null || echo /usr/lib/postgresql/16/bin/initdb)")}"
if [ -x "$PGB/initdb" ] && "$PGB/initdb" --version | grep -q " 16\."; then PGBIN="$PGB" bash verification/validate_db.sh; else echo "db: skipped (PostgreSQL 16 not available; set PGBIN)"; fi
