"""Run the worked traces, write outputs, and cross-check arithmetic independently.

Usage:  python3 verification/run_traces.py        (from the pack root)
Writes: fixtures/claims/*.output.json and verification/trace-report.md
Exit code is non-zero if any cross-check fails.
"""
import json
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "verification"))
from engine import evaluate, D, q2, money  # noqa: E402

policy = json.loads((ROOT / "config/policy-ILL-INDEMNITY-A.v2026.1.0.json").read_text())
nme = json.loads((ROOT / "config/nme-list-ILL-A.v2026.1.0.json").read_text())
tariff = json.loads((ROOT / "config/tariff-ILL-HOSP-NW-01.v2026.07.json").read_text())
checklist = json.loads((ROOT / "config/checklist-IPD-REIMB.v2026.1.0.json").read_text())

TRACES = [
    ("trace-1-straightforward", None),
    ("trace-2-interacting-adjustments", tariff),
    ("trace-2b-reviewer-override", tariff),
    ("trace-3a-insufficient-conflicting", None),
    ("trace-3b-after-new-evidence", None),
]

failures = []


def check(cond, msg):
    if not cond:
        failures.append(msg)
    return cond


def reconcile(out):
    """Invariant: billed = payable + sum(all adjustments) when computed; per-line deductions never exceed billed."""
    rec = out["recommendation"]
    adj_total = sum((D(a["amount"]) for a in out["adjustments"]), Decimal("0"))
    if rec["computed"]:
        check(D(rec["billed_total"]) == D(rec["recommended_payable"]) + adj_total,
              f"{out['claim_id']}: billed != payable + adjustments")
    per_line = {}
    for a in out["adjustments"]:
        if a["level"] == "LINE":
            per_line[a["line_id"]] = per_line.get(a["line_id"], Decimal("0")) + D(a["amount"])
    for l in out["lines"]:
        check(per_line.get(l["line_id"], Decimal("0")) <= D(l["billed"]), f"{out['claim_id']} {l['line_id']}: over-deducted")
        if l["payable"] is not None:
            check(D(l["billed"]) - per_line.get(l["line_id"], Decimal("0")) == D(l["payable"]), f"{out['claim_id']} {l['line_id']}: line payable mismatch")
    return adj_total


def independent_trace2():
    """Hand-derived arithmetic for trace 2, written without the engine, as a cross-check."""
    billed = sum(map(Decimal, ["18000", "9000", "4500", "3000", "45000", "12000", "28000", "4000", "2500",
                               "3420", "3420", "11865.75", "14500", "5500", "4850", "600", "350", "1800", "150"]))
    duplicate = Decimal("3420")
    nme_total = Decimal("600") + Decimal("350") + Decimal("1800") + Decimal("150")
    tariff_total = (Decimal("45000") - Decimal("35000")) + (Decimal("5500") - Decimal("4000"))
    room = 3 * (Decimal("6000") - Decimal("3000")) + (Decimal("9000") - Decimal("6000"))
    ratio = Decimal("3000") / Decimal("6000")
    prop_bases = [Decimal("4500"), Decimal("35000"), Decimal("12000"), Decimal("28000"), Decimal("4000")]
    prop = sum(b - (b * ratio) for b in prop_bases)
    admissible = billed - duplicate - nme_total - tariff_total - room - prop
    copay = (admissible * Decimal("0.10")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    after_copay = admissible - copay
    available = Decimal("300000") + Decimal("30000") - Decimal("245000")
    payable = min(after_copay, available)
    # Sensitivity: if SI cap were applied before co-pay (a different policy wording), payable would be:
    alt = min(admissible, available)
    alt_payable = alt - (alt * Decimal("0.10")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return {"billed": billed, "admissible": admissible, "copay": copay, "after_copay": after_copay,
            "available_si": available, "payable": payable, "alt_order_payable": alt_payable}


report = ["# Trace verification report", "",
          "Generated by `verification/run_traces.py`. Each trace is evaluated by the reference harness; "
          "outputs are reconciled (billed = payable + all adjustments) and trace 2 is recomputed by an independent hand-coded formula.", ""]

for name, trf in TRACES:
    claim = json.loads((ROOT / f"fixtures/claims/{name}.input.json").read_text())
    out = evaluate(claim, policy, nme, trf, checklist)
    out2 = evaluate(json.loads((ROOT / f"fixtures/claims/{name}.input.json").read_text()), policy, nme, trf, checklist)
    check(out["output_hash"] == out2["output_hash"], f"{name}: non-deterministic output")
    adj_total = reconcile(out)
    (ROOT / f"fixtures/claims/{name}.output.json").write_text(json.dumps(out, indent=2) + "\n")
    rec = out["recommendation"]
    report += [f"## {name}", "",
               f"- Recommendation: **{rec['type']}**; computed: {rec['computed']}; recommended payable: {rec['recommended_payable']}",
               f"- Billed {rec['billed_total']}; line-level deductions {rec['line_level_deductions']}; claim-level {rec['claim_level_deductions']}; "
               f"all adjustments {money(adj_total)}",
               f"- Blocked scopes: {rec['blocked_scopes'] or 'none'}; findings: {len(out['findings'])}; query items: {len(out['query_items'])}",
               f"- Output hash: `{out['output_hash']}` (re-run identical: {out['output_hash'] == out2['output_hash']})", ""]

ind = independent_trace2()
out2 = json.loads((ROOT / "fixtures/claims/trace-2-interacting-adjustments.output.json").read_text())
check(D(out2["recommendation"]["recommended_payable"]) == q2(ind["payable"]), "trace 2: engine payable != independent payable")
check(D(out2["recommendation"]["admissible_after_line_rules"]) == q2(ind["admissible"]), "trace 2: admissible mismatch")
report += ["## Independent cross-check of trace 2", "",
           f"- Billed {money(ind['billed'])}; admissible after line rules {money(ind['admissible'])}; co-pay {money(ind['copay'])}; "
           f"after co-pay {money(ind['after_copay'])}; available SI {money(ind['available_si'])}; payable {money(ind['payable'])}",
           f"- Engine payable {out2['recommendation']['recommended_payable']} — match: {D(out2['recommendation']['recommended_payable']) == q2(ind['payable'])}",
           f"- Order sensitivity: applying the SI cap *before* co-pay would give {money(ind['alt_order_payable'])} "
           f"(difference {money(ind['payable'] - ind['alt_order_payable'])}). Calculation order is therefore a policy-wording input, not an engine default.", ""]

ob = json.loads((ROOT / "fixtures/claims/trace-2b-reviewer-override.output.json").read_text())
ov = [a for a in ob["adjustments"] if a["origin"] == "REVIEWER_OVERRIDE"]
check(len(ov) == 1 and ov[0]["line_id"] == "L14" and ov[0]["amount"] == "0.00" and ov[0]["engine_amount"] == "1500.00", "trace 2b: override not applied as specified")
check(D(ob["recommendation"]["admissible_after_line_rules"]) == q2(ind["admissible"]) + 1500, "trace 2b: admissible should rise by the overridden 1,500.00")
check(ob["input_hash"] != json.loads((ROOT / "fixtures/claims/trace-2-interacting-adjustments.output.json").read_text())["input_hash"], "trace 2b: input hash must differ from trace 2")
report += ["## Reviewer override (trace 2b)", "",
           f"- Override RA-0207 sets the CT tariff deduction on L14 to 0.00 (engine computed {ov[0]['engine_amount'] if ov else '?'}); admissible becomes "
           f"{ob['recommendation']['admissible_after_line_rules']}; payable stays {ob['recommendation']['recommended_payable']} because the sum-insured cap still binds.", ""]

report += ["## Result", "", "All checks passed." if not failures else "FAILURES:\n" + "\n".join(f"- {f}" for f in failures), ""]
(ROOT / "verification/trace-report.md").write_text("\n".join(report))
print("\n".join(report))
sys.exit(1 if failures else 0)
