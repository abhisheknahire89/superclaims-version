"""Create workbench/.env with freshly generated local development secrets (stdlib only).

    python3 scripts/make_env.py [path]        # default: .env next to the Makefile; never overwrites an existing file

The file is created with mode 600 and is git-ignored. Values are never printed or logged. It holds:
  AW_SECRET_KEY            signs session tokens and short-lived page/upload URLs
  AW_DB_*_PASSWORD         passwords for the local PostgreSQL roles (owner is used only by docker compose)
Synthetic seed accounts use the public development password documented in README.
"""
from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path


def generate(path: Path) -> bool:
    if path.exists():
        return False
    word = lambda n: secrets.token_urlsafe(n).replace("-", "x").replace("_", "y")  # noqa: E731  (shell- and DSN-safe)
    values = {
        "AW_ENV": "dev",
        "AW_SECRET_KEY": secrets.token_urlsafe(48),
        "AW_DB_OWNER_PASSWORD": word(24),
        "AW_DB_APP_PASSWORD": word(24),
        "AW_DB_WORKER_PASSWORD": word(24),
    }
    body = ["# Local development secrets, generated by scripts/make_env.py. Never commit, share or print this file.",
            "# Synthetic demo passwords are documented in README; these values protect local services."]
    body += [f"{k}={v}" for k, v in values.items()]
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("\n".join(body) + "\n")
    return True


def load(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


if __name__ == "__main__":
    target = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / ".env")
    created = generate(target)
    print(f"{'created' if created else 'kept existing'} {target.name} (values not shown)")
