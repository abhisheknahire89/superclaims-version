CREATE OR REPLACE FUNCTION forbid_update_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'table % is append-only', TG_TABLE_NAME;
END $$;

CREATE TRIGGER audit_event_append_only BEFORE UPDATE OR DELETE ON audit_event FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
CREATE TRIGGER adjustment_append_only BEFORE UPDATE OR DELETE ON adjustment FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
CREATE TRIGGER rule_execution_append_only BEFORE UPDATE OR DELETE ON rule_execution FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
CREATE TRIGGER reviewer_action_append_only BEFORE UPDATE OR DELETE ON reviewer_action FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
CREATE TRIGGER decision_append_only BEFORE UPDATE OR DELETE ON decision FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
CREATE TRIGGER extracted_fact_append_only BEFORE UPDATE OR DELETE ON extracted_fact FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();

-- ---------- row-level security (pooled multi-tenant mode) ----------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['app_user','role_assignment','config_artifact','hospital','member','policy','policy_member','si_ledger_entry',
                           'claim','document','document_page','processing_job','extraction_run','extracted_fact','resolved_fact','bill_line',
                           'evaluation','rule_execution','adjustment','finding','query_letter','query_item','reviewer_action','decision',
                           'approval_request','adjustment_override','idempotency_key','webhook_delivery','export_record','audit_event']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY tenant_isolation ON %I USING (tenant_id = current_setting(''app.tenant_id'', true)) WITH CHECK (tenant_id = current_setting(''app.tenant_id'', true))', t);
  END LOOP;
END $$;

COMMIT;
