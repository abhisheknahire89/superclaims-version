-- Adjudication Workbench — proposed PostgreSQL 16 schema (PROPOSED, not observed from any competitor)
-- Conventions
--   * Money: BIGINT paise. Amounts are non-negative unless the column comment says otherwise.
--   * Dates: DATE for clinical/policy dates (no time zone); TIMESTAMPTZ for system events (stored UTC, displayed IST).
--   * Every tenant-owned row carries tenant_id; row-level security (RLS) enforces isolation in pooled mode.
--   * Rows that represent evidence or decisions are append-only (enforced by trigger); corrections create new rows.
--   * IDs are UUIDv7-style text generated by the application (sortable); DB defaults use gen_random_uuid() for convenience.
-- Validated by: verification/validate_db.sh (initdb + psql -v ON_ERROR_STOP=1 + load of trace outputs)

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------- enums ----------
CREATE TYPE workflow_type AS ENUM ('PREAUTH', 'ENHANCEMENT', 'CASHLESS_DISCHARGE', 'IPD_REIMBURSEMENT', 'OPD_REIMBURSEMENT', 'OPD_CASHLESS');
CREATE TYPE claim_status AS ENUM ('INTAKE', 'DOCS_INCOMPLETE', 'PROCESSING', 'READY_FOR_REVIEW', 'IN_REVIEW', 'MEDICAL_REVIEW',
                                  'QUERY_RAISED', 'AWAITING_RESPONSE', 'PENDING_APPROVAL', 'ESCALATED_CRC', 'FINALISED', 'EXPORTED',
                                  'REOPENED', 'WITHDRAWN');
CREATE TYPE doc_status AS ENUM ('RECEIVED', 'STORED', 'CLASSIFYING', 'CLASSIFIED', 'EXTRACTING', 'EXTRACTED', 'NEEDS_REVIEW',
                                'FAILED_UNREADABLE', 'FAILED_TECHNICAL', 'QUARANTINED', 'SUPERSEDED');
CREATE TYPE evaluation_status AS ENUM ('RUNNING', 'COMPUTED', 'BLOCKED', 'FAILED', 'STALE', 'SUPERSEDED');
CREATE TYPE recommendation_type AS ENUM ('PAY_FULL', 'PAY_PARTIAL', 'QUERY', 'QUERY_AND_REFER_MEDICAL', 'REFER_MEDICAL', 'REFER_CRC', 'INVESTIGATE');
-- A query is a workflow step (claim_status QUERY_RAISED), not a disposition.
CREATE TYPE disposition_type AS ENUM ('APPROVED_FULL', 'APPROVED_PARTIAL', 'REPUDIATED_WITH_CRC_APPROVAL', 'WITHDRAWN', 'CLOSED_DUPLICATE');
CREATE TYPE finding_status AS ENUM ('OPEN', 'ACKNOWLEDGED', 'RESOLVED', 'DISMISSED', 'SUPERSEDED');
CREATE TYPE severity AS ENUM ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL');
CREATE TYPE query_status AS ENUM ('DRAFT', 'APPROVED', 'SENT', 'PARTIALLY_ANSWERED', 'ANSWERED', 'CLOSED', 'CANCELLED');
CREATE TYPE adjustment_level AS ENUM ('LINE', 'CLAIM');
CREATE TYPE actor_kind AS ENUM ('USER', 'SYSTEM', 'INTEGRATION');

-- ---------- tenancy & access ----------
CREATE TABLE tenant (
  tenant_id        TEXT PRIMARY KEY,
  legal_name       TEXT NOT NULL,
  tenant_kind      TEXT NOT NULL CHECK (tenant_kind IN ('INSURER', 'TPA')),
  data_region      TEXT NOT NULL DEFAULT 'ap-south-1',
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app_user (
  user_id          TEXT PRIMARY KEY,
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  idp_subject      TEXT NOT NULL,                       -- OIDC 'sub'; no passwords stored here
  display_name     TEXT NOT NULL,
  is_active        BOOLEAN NOT NULL DEFAULT true,
  UNIQUE (tenant_id, idp_subject)
);

CREATE TABLE role_assignment (
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  user_id          TEXT NOT NULL REFERENCES app_user,
  role             TEXT NOT NULL CHECK (role IN ('PROCESSOR', 'MEDICAL_OFFICER', 'SUPERVISOR', 'AUDITOR', 'FWA_ANALYST', 'CONFIG_ADMIN', 'TENANT_ADMIN', 'READ_ONLY')),
  approval_limit_paise BIGINT CHECK (approval_limit_paise IS NULL OR approval_limit_paise >= 0),
  valid_from       TIMESTAMPTZ NOT NULL DEFAULT now(),
  valid_to         TIMESTAMPTZ,
  PRIMARY KEY (tenant_id, user_id, role, valid_from)
);

-- ---------- reference & configuration (versioned, immutable once published) ----------
CREATE TABLE config_artifact (
  artifact_id      TEXT NOT NULL,                       -- e.g. POLCFG-ILL-INDEMNITY-A, NMELIST-ILL-A, TARIFF-ILL-HOSP-NW-01
  version          TEXT NOT NULL,                       -- semantic or calendar version
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  artifact_kind    TEXT NOT NULL CHECK (artifact_kind IN ('POLICY_CONFIG', 'NME_LIST', 'TARIFF', 'CHECKLIST', 'WORKFLOW_CONFIG', 'RULE_PACK', 'CLASSIFIER_MAP')),
  status           TEXT NOT NULL CHECK (status IN ('DRAFT', 'IN_REVIEW', 'PUBLISHED', 'RETIRED')),
  effective_from   DATE NOT NULL,
  effective_to     DATE,
  body             JSONB NOT NULL,                      -- validated against schemas/*.schema.json before publish
  body_sha256      TEXT NOT NULL,
  source_documents JSONB NOT NULL DEFAULT '[]',         -- authoritative wording / circular / tariff agreement references
  authored_by      TEXT REFERENCES app_user,
  approved_by      TEXT REFERENCES app_user,            -- four-eyes: must differ from authored_by
  published_at     TIMESTAMPTZ,
  PRIMARY KEY (tenant_id, artifact_id, version),
  CHECK (effective_to IS NULL OR effective_to >= effective_from),
  CHECK (status <> 'PUBLISHED' OR (approved_by IS NOT NULL AND approved_by IS DISTINCT FROM authored_by))
);

CREATE TABLE hospital (
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  hospital_id      TEXT NOT NULL,
  name             TEXT NOT NULL,
  rohini_id        TEXT,                                -- registry ID if the customer supplies it
  city             TEXT,
  is_network       BOOLEAN NOT NULL DEFAULT false,
  PRIMARY KEY (tenant_id, hospital_id)
);

-- ---------- policy & member ----------
CREATE TABLE member (
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  member_id        TEXT NOT NULL,
  full_name        TEXT NOT NULL,                       -- PII: column-level encryption recommended (see 08)
  name_normalised  TEXT NOT NULL,
  gender           TEXT CHECK (gender IN ('F', 'M', 'X', 'U')),
  dob              DATE,
  abha_number_hash TEXT,                                -- store only a keyed hash unless the customer requires the raw value
  PRIMARY KEY (tenant_id, member_id)
);

CREATE TABLE policy (
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  policy_no        TEXT NOT NULL,
  product_name     TEXT NOT NULL,
  product_uin      TEXT,
  period_start     DATE NOT NULL,
  period_end       DATE NOT NULL,
  config_artifact_id TEXT NOT NULL,
  config_version   TEXT NOT NULL,
  PRIMARY KEY (tenant_id, policy_no),
  FOREIGN KEY (tenant_id, config_artifact_id, config_version) REFERENCES config_artifact (tenant_id, artifact_id, version),
  CHECK (period_end >= period_start)
);

CREATE TABLE policy_member (
  tenant_id        TEXT NOT NULL,
  policy_no        TEXT NOT NULL,
  member_id        TEXT NOT NULL,
  continuous_cover_since DATE NOT NULL,
  base_sum_insured_paise BIGINT NOT NULL CHECK (base_sum_insured_paise > 0),
  cumulative_bonus_paise BIGINT NOT NULL DEFAULT 0 CHECK (cumulative_bonus_paise >= 0),
  declared_peds    JSONB NOT NULL DEFAULT '[]',
  PRIMARY KEY (tenant_id, policy_no, member_id),
  FOREIGN KEY (tenant_id, policy_no) REFERENCES policy,
  FOREIGN KEY (tenant_id, member_id) REFERENCES member
);

-- Sum-insured utilisation is a ledger, not a mutable balance, so concurrent claims cannot double-spend it.
CREATE TABLE si_ledger_entry (
  entry_id         TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  tenant_id        TEXT NOT NULL,
  policy_no        TEXT NOT NULL,
  member_id        TEXT NOT NULL,
  policy_year_start DATE NOT NULL,
  claim_id         TEXT,
  entry_kind       TEXT NOT NULL CHECK (entry_kind IN ('OPENING_PAID_EXTERNAL', 'RESERVED', 'RELEASED', 'PAID')),
  amount_paise     BIGINT NOT NULL CHECK (amount_paise >= 0),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (tenant_id, policy_no, member_id) REFERENCES policy_member
);

-- ---------- claim ----------
CREATE TABLE claim (
  tenant_id        TEXT NOT NULL REFERENCES tenant,
  claim_id         TEXT NOT NULL,
  external_ref     TEXT,                                -- TMS / insurer claim number
  workflow         workflow_type NOT NULL,
  status           claim_status NOT NULL DEFAULT 'INTAKE',
  policy_no        TEXT NOT NULL,
  member_id        TEXT NOT NULL,
  hospital_id      TEXT,
  admission_date   DATE,                                -- established value (after conflict resolution); NULL while disputed
  discharge_date   DATE,
  intimated_at     TIMESTAMPTZ,                         -- interest on late settlement runs from receipt of intimation (E-REG-03)
  submitted_at     TIMESTAMPTZ,                         -- first submission of the claim: start of the 15-day reimbursement clock (E-REG-03); query-pause unresolved (OQ-21)
  investigation_hold BOOLEAN NOT NULL DEFAULT false,    -- placed/released by FWA_ANALYST or SUPERVISOR (reviewer_action)
  assigned_to      TEXT REFERENCES app_user,
  current_evaluation_id TEXT,
  row_version      INTEGER NOT NULL DEFAULT 1,          -- optimistic concurrency for status transitions
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, claim_id),
  UNIQUE (tenant_id, external_ref),
  FOREIGN KEY (tenant_id, policy_no, member_id) REFERENCES policy_member,
  FOREIGN KEY (tenant_id, hospital_id) REFERENCES hospital,
  CHECK (discharge_date IS NULL OR admission_date IS NULL OR discharge_date >= admission_date)
);
CREATE INDEX claim_queue_idx ON claim (tenant_id, status, submitted_at);

-- ---------- documents & evidence ----------
CREATE TABLE document (
  tenant_id        TEXT NOT NULL,
  document_id      TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  declared_type    TEXT,                                -- as declared by the sender
  classified_type  TEXT,                                -- as classified (may differ; reviewer can correct)
  status           doc_status NOT NULL DEFAULT 'RECEIVED',
  source_channel   TEXT NOT NULL CHECK (source_channel IN ('API', 'PORTAL_UPLOAD', 'TMS_SYNC', 'EMAIL_INGEST', 'NHCX')),
  object_key       TEXT NOT NULL,                       -- immutable original in object storage (WORM bucket)
  sha256           TEXT NOT NULL,
  mime_type        TEXT NOT NULL,
  page_count       INTEGER CHECK (page_count IS NULL OR page_count >= 0),
  supersedes_document_id TEXT,
  received_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, document_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  UNIQUE (tenant_id, claim_id, sha256)                  -- exact duplicate uploads are idempotent
);

CREATE TABLE document_page (
  tenant_id        TEXT NOT NULL,
  document_id      TEXT NOT NULL,
  page_no          INTEGER NOT NULL CHECK (page_no >= 1),
  text_layer       TEXT NOT NULL CHECK (text_layer IN ('NATIVE', 'OCR', 'NONE')),
  ocr_engine       TEXT,
  quality_score    NUMERIC(4,3) CHECK (quality_score BETWEEN 0 AND 1),
  image_key        TEXT,
  text_key         TEXT,                                -- OCR JSON with word boxes in object storage
  language_hint    TEXT,
  PRIMARY KEY (tenant_id, document_id, page_no),
  FOREIGN KEY (tenant_id, document_id) REFERENCES document
);

CREATE TABLE processing_job (
  job_id           TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  tenant_id        TEXT NOT NULL,
  job_kind         TEXT NOT NULL CHECK (job_kind IN ('CLASSIFY', 'OCR', 'EXTRACT', 'RECONCILE', 'EVALUATE', 'EXPORT', 'WEBHOOK')),
  subject_id       TEXT NOT NULL,                       -- document_id / claim_id
  idempotency_key  TEXT NOT NULL,
  state            TEXT NOT NULL CHECK (state IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED_RETRYABLE', 'FAILED_FINAL', 'CANCELLED')),
  attempts         INTEGER NOT NULL DEFAULT 0,
  max_attempts     INTEGER NOT NULL DEFAULT 5,
  run_after        TIMESTAMPTZ NOT NULL DEFAULT now(),
  locked_by        TEXT,
  locked_until     TIMESTAMPTZ,
  last_error_code  TEXT,                                -- never raw document text (see 08)
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, job_kind, idempotency_key)
);
CREATE INDEX job_pick_idx ON processing_job (state, run_after) WHERE state IN ('QUEUED', 'FAILED_RETRYABLE');

CREATE TABLE extraction_run (
  tenant_id        TEXT NOT NULL,
  extraction_run_id TEXT NOT NULL,
  document_id      TEXT NOT NULL,
  pipeline_version TEXT NOT NULL,
  model_ref        TEXT,                                -- provider/model/version actually called
  prompt_version   TEXT,
  started_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at      TIMESTAMPTZ,
  outcome          TEXT NOT NULL CHECK (outcome IN ('OK', 'PARTIAL', 'FAILED')),
  PRIMARY KEY (tenant_id, extraction_run_id),
  FOREIGN KEY (tenant_id, document_id) REFERENCES document
);

CREATE TABLE extracted_fact (
  tenant_id        TEXT NOT NULL,
  fact_id          TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  extraction_run_id TEXT NOT NULL,
  field_path       TEXT NOT NULL,                       -- e.g. patient.name, admission.date, bill.total
  raw_value        TEXT,
  normalised_value JSONB,
  confidence       NUMERIC(4,3) CHECK (confidence BETWEEN 0 AND 1),
  evidence         JSONB NOT NULL,                      -- {document_id, page, bbox[x0,y0,x1,y1], quote}
  grounding_check  TEXT NOT NULL CHECK (grounding_check IN ('VERIFIED', 'NOT_FOUND', 'NOT_APPLICABLE')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, fact_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  FOREIGN KEY (tenant_id, extraction_run_id) REFERENCES extraction_run
);
CREATE INDEX fact_claim_field_idx ON extracted_fact (tenant_id, claim_id, field_path);

-- The value the rules use. One row per (claim, field) per resolution; latest active wins.
CREATE TABLE resolved_fact (
  tenant_id        TEXT NOT NULL,
  resolved_fact_id TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  field_path       TEXT NOT NULL,
  value            JSONB,
  basis            TEXT NOT NULL CHECK (basis IN ('AUTO_AGREEMENT', 'AUTO_SINGLE_SOURCE', 'REVIEWER_SELECTED', 'REVIEWER_ENTERED', 'UNRESOLVED')),
  source_fact_ids  TEXT[] NOT NULL DEFAULT '{}',
  reviewer_action_id TEXT,
  is_active        BOOLEAN NOT NULL DEFAULT true,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, resolved_fact_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim
);
CREATE UNIQUE INDEX resolved_fact_active_uq ON resolved_fact (tenant_id, claim_id, field_path) WHERE is_active;

CREATE TABLE bill_line (
  tenant_id        TEXT NOT NULL,
  bill_line_id     TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  bill_version     INTEGER NOT NULL,                    -- increments when a new bill supersedes the old
  line_no          TEXT NOT NULL,                       -- e.g. L05
  description      TEXT NOT NULL,
  category         TEXT NOT NULL,
  category_source  TEXT NOT NULL CHECK (category_source IN ('DICTIONARY', 'MODEL', 'REVIEWER')),
  category_confidence NUMERIC(4,3),
  ward_context     TEXT NOT NULL DEFAULT 'WARD' CHECK (ward_context IN ('WARD', 'ICU', 'DAYCARE', 'OPD', 'UNKNOWN')),
  room_category    TEXT,
  service_date     DATE,
  invoice_no       TEXT,
  quantity         NUMERIC(12,3) NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_rate_paise  BIGINT CHECK (unit_rate_paise IS NULL OR unit_rate_paise >= 0),
  billed_paise     BIGINT NOT NULL CHECK (billed_paise >= 0),
  evidence         JSONB NOT NULL DEFAULT '[]',
  is_active        BOOLEAN NOT NULL DEFAULT true,
  PRIMARY KEY (tenant_id, bill_line_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  UNIQUE (tenant_id, claim_id, bill_version, line_no)
);

-- ---------- evaluation (rule run) ----------
CREATE TABLE evaluation (
  tenant_id        TEXT NOT NULL,
  evaluation_id    TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  evaluation_no    INTEGER NOT NULL,
  supersedes_evaluation_id TEXT,
  trigger          TEXT NOT NULL CHECK (trigger IN ('INITIAL', 'NEW_EVIDENCE', 'REVIEWER_CORRECTION', 'CONFIG_CHANGE', 'MANUAL_RERUN')),
  status           evaluation_status NOT NULL,
  engine_version   TEXT NOT NULL,
  config_versions  JSONB NOT NULL,                      -- exact artifact@version list used
  input_hash       TEXT NOT NULL,
  output_hash      TEXT,
  recommendation   recommendation_type,
  recommended_payable_paise BIGINT CHECK (recommended_payable_paise IS NULL OR recommended_payable_paise >= 0),
  billed_total_paise BIGINT CHECK (billed_total_paise IS NULL OR billed_total_paise >= 0),
  blocked_scopes   TEXT[] NOT NULL DEFAULT '{}',
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, evaluation_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  UNIQUE (tenant_id, claim_id, evaluation_no),
  UNIQUE (tenant_id, claim_id, input_hash, engine_version), -- identical re-run is idempotent
  CHECK (status <> 'COMPUTED' OR recommended_payable_paise IS NOT NULL),
  CHECK (status <> 'BLOCKED' OR recommended_payable_paise IS NULL)
);
ALTER TABLE claim ADD CONSTRAINT claim_current_eval_fk FOREIGN KEY (tenant_id, current_evaluation_id) REFERENCES evaluation (tenant_id, evaluation_id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE rule_execution (
  tenant_id        TEXT NOT NULL,
  rule_execution_id TEXT NOT NULL,
  evaluation_id    TEXT NOT NULL,
  step_no          INTEGER NOT NULL,
  rule_id          TEXT NOT NULL,
  rule_version     TEXT NOT NULL,
  status           TEXT NOT NULL CHECK (status IN ('PASSED', 'FAILED', 'APPLIED', 'NOT_APPLICABLE', 'REVIEW', 'BLOCKED', 'SKIPPED_BLOCKED', 'FLAGGED')),
  detail           JSONB NOT NULL DEFAULT '{}',
  PRIMARY KEY (tenant_id, rule_execution_id),
  FOREIGN KEY (tenant_id, evaluation_id) REFERENCES evaluation,
  UNIQUE (tenant_id, evaluation_id, step_no)
);

CREATE TABLE adjustment (
  tenant_id        TEXT NOT NULL,
  adjustment_id    TEXT NOT NULL,
  evaluation_id    TEXT NOT NULL,
  rule_execution_id TEXT NOT NULL,
  level            adjustment_level NOT NULL,
  bill_line_id     TEXT,
  reason_code      TEXT NOT NULL,
  amount_paise     BIGINT NOT NULL,                     -- applied amount; positive reduces payable; negative allowed only for ROUNDING
  engine_amount_paise BIGINT NOT NULL,                  -- what the engine computed before any reviewer override
  base_before_paise BIGINT NOT NULL CHECK (base_before_paise >= 0),
  remaining_after_paise BIGINT NOT NULL CHECK (remaining_after_paise >= 0),
  formula          TEXT NOT NULL,
  explanation      TEXT NOT NULL,
  authority        JSONB NOT NULL,                      -- {artifact: 'id@version', doc_id, clause}; required for every adjustment
  evidence         JSONB NOT NULL DEFAULT '[]',
  origin           TEXT NOT NULL DEFAULT 'ENGINE' CHECK (origin IN ('ENGINE', 'REVIEWER_OVERRIDE', 'REVIEWER_ADDED')),
  override_ref     TEXT,
  PRIMARY KEY (tenant_id, adjustment_id),
  FOREIGN KEY (tenant_id, evaluation_id) REFERENCES evaluation,
  FOREIGN KEY (tenant_id, rule_execution_id) REFERENCES rule_execution,
  FOREIGN KEY (tenant_id, bill_line_id) REFERENCES bill_line,
  CHECK ((level = 'LINE') = (bill_line_id IS NOT NULL)),
  CHECK (amount_paise >= 0 OR reason_code = 'ROUNDING'),
  CHECK (amount_paise <= base_before_paise),
  CHECK (authority ? 'artifact' AND authority ? 'clause' AND authority ? 'doc_id'),
  CHECK (jsonb_typeof(evidence) = 'array' AND jsonb_array_length(evidence) > 0),
  CHECK ((origin = 'REVIEWER_OVERRIDE') = (override_ref IS NOT NULL)),
  UNIQUE (tenant_id, evaluation_id, bill_line_id, rule_execution_id)   -- one deduction per rule per line per run
);

-- ---------- findings, queries, review, decision ----------
CREATE TABLE finding (
  tenant_id        TEXT NOT NULL,
  finding_id       TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  first_evaluation_id TEXT NOT NULL,
  last_evaluation_id TEXT NOT NULL,
  rule_id          TEXT NOT NULL,
  category         TEXT NOT NULL CHECK (category IN ('DOCUMENT', 'IDENTITY', 'ELIGIBILITY', 'FINANCIAL', 'CLINICAL', 'ANOMALY')),
  kind             TEXT NOT NULL,
  severity         severity NOT NULL,
  blocking         BOOLEAN NOT NULL,
  blocked_scopes   TEXT[] NOT NULL DEFAULT '{}',          -- ALL_FINANCIAL | LINE_RULES | ROOM_DAYS | WAITING_PERIOD | PRE_POST_WINDOW
  route_to         TEXT,
  summary          TEXT NOT NULL,
  uncertainty_note TEXT,                                -- required for CLINICAL and ANOMALY (see check)
  evidence         JSONB NOT NULL DEFAULT '[]',
  status           finding_status NOT NULL DEFAULT 'OPEN',
  resolution       JSONB,
  PRIMARY KEY (tenant_id, finding_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  CHECK (category NOT IN ('CLINICAL', 'ANOMALY') OR uncertainty_note IS NOT NULL),
  CHECK (jsonb_typeof(evidence) = 'array')
);

CREATE TABLE query_letter (
  tenant_id        TEXT NOT NULL,
  query_id         TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  addressed_to     TEXT NOT NULL CHECK (addressed_to IN ('HOSPITAL', 'CLAIMANT', 'INSURER', 'TPA', 'INVESTIGATOR')),
  status           query_status NOT NULL DEFAULT 'DRAFT',
  approved_by      TEXT REFERENCES app_user,
  sent_at          TIMESTAMPTZ,
  due_at           TIMESTAMPTZ,
  reminder_count   INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (tenant_id, query_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  CHECK (status NOT IN ('SENT', 'PARTIALLY_ANSWERED', 'ANSWERED') OR approved_by IS NOT NULL)
);

CREATE TABLE query_item (
  tenant_id        TEXT NOT NULL,
  query_item_id    TEXT NOT NULL,
  query_id         TEXT NOT NULL,
  requested_document_type TEXT,
  text             TEXT NOT NULL,
  linked_finding_ids TEXT[] NOT NULL DEFAULT '{}',
  answered_by_document_id TEXT,
  status           TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ANSWERED', 'WAIVED')),
  PRIMARY KEY (tenant_id, query_item_id),
  FOREIGN KEY (tenant_id, query_id) REFERENCES query_letter
);

CREATE TABLE reviewer_action (
  tenant_id        TEXT NOT NULL,
  reviewer_action_id TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  evaluation_id    TEXT,
  actor_user_id    TEXT NOT NULL REFERENCES app_user,
  action           TEXT NOT NULL CHECK (action IN ('CORRECT_FACT', 'RESOLVE_CONFLICT', 'RECLASSIFY_LINE', 'RECLASSIFY_DOCUMENT', 'MARK_PAGE_UNREADABLE',
                                                   'OVERRIDE_ADJUSTMENT', 'ADD_ADJUSTMENT', 'REMOVE_ADJUSTMENT', 'ACKNOWLEDGE_FINDING', 'RESOLVE_FINDING',
                                                   'DISMISS_FINDING', 'RETURN_FOR_REWORK', 'ESCALATE_MEDICAL', 'ESCALATE_CRC', 'ESCALATE_FWA',
                                                   'PLACE_INVESTIGATION_HOLD', 'RELEASE_INVESTIGATION_HOLD', 'RECORD_CRC_DECLINED')),   -- approvals, assignment, reopen, withdraw are commands with their own tables/audit events
  target_ref       JSONB NOT NULL,                      -- {type, id}
  before_value     JSONB,
  after_value      JSONB,
  reason_code      TEXT NOT NULL,
  comment          TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, reviewer_action_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  CHECK (action NOT IN ('OVERRIDE_ADJUSTMENT', 'ADD_ADJUSTMENT', 'REMOVE_ADJUSTMENT', 'DISMISS_FINDING') OR comment IS NOT NULL)
);

CREATE TABLE decision (
  tenant_id        TEXT NOT NULL,
  decision_id      TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  evaluation_id    TEXT NOT NULL,
  disposition      disposition_type NOT NULL,
  approved_payable_paise BIGINT CHECK (approved_payable_paise IS NULL OR approved_payable_paise >= 0),
  decided_by       TEXT NOT NULL REFERENCES app_user,
  second_approver  TEXT REFERENCES app_user,
  crc_reference    TEXT,                                -- insurer Claims Review Committee approval reference
  communicated_by  TEXT NOT NULL DEFAULT 'TPA' CHECK (communicated_by IN ('INSURER', 'TPA')),  -- repudiation is communicated only by the insurer (E-REG-04)
  duplicate_of_claim_id TEXT,
  deviation_from_recommendation_paise BIGINT,
  letter_document_id TEXT,
  decided_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, decision_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  FOREIGN KEY (tenant_id, evaluation_id) REFERENCES evaluation,
  CHECK (disposition <> 'REPUDIATED_WITH_CRC_APPROVAL' OR (crc_reference IS NOT NULL AND communicated_by = 'INSURER')),
  CHECK (disposition <> 'CLOSED_DUPLICATE' OR duplicate_of_claim_id IS NOT NULL),
  CHECK (disposition NOT IN ('APPROVED_FULL', 'APPROVED_PARTIAL') OR approved_payable_paise IS NOT NULL),
  CHECK (second_approver IS NULL OR second_approver <> decided_by)
);
CREATE UNIQUE INDEX one_final_decision_per_eval ON decision (tenant_id, evaluation_id);

-- Second-approval workflow: a proposed decision waits here; the decision row is written only when approved.
CREATE TABLE approval_request (
  tenant_id        TEXT NOT NULL,
  approval_request_id TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  evaluation_id    TEXT NOT NULL,
  proposed_disposition disposition_type NOT NULL,
  proposed_payable_paise BIGINT CHECK (proposed_payable_paise IS NULL OR proposed_payable_paise >= 0),
  requested_by     TEXT NOT NULL REFERENCES app_user,
  approver         TEXT NOT NULL REFERENCES app_user,
  triggers         TEXT[] NOT NULL,                     -- e.g. {PAYABLE_ABOVE_APPROVER_LIMIT, TOTAL_DEDUCTIONS_ABOVE_SHARE_OF_BILLED}
  state            TEXT NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'APPROVED', 'RETURNED', 'CANCELLED')),
  decided_at       TIMESTAMPTZ,
  comment          TEXT,
  PRIMARY KEY (tenant_id, approval_request_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim,
  FOREIGN KEY (tenant_id, evaluation_id) REFERENCES evaluation,
  CHECK (approver <> requested_by),
  CHECK (state <> 'RETURNED' OR comment IS NOT NULL)
);

-- Reviewer override directives survive re-evaluation: re-applied only if the bill line's fingerprint is unchanged.
CREATE TABLE adjustment_override (
  tenant_id        TEXT NOT NULL,
  override_id      TEXT NOT NULL,
  claim_id         TEXT NOT NULL,
  line_no          TEXT NOT NULL,                       -- natural key within the claim's bill (with bill_version)
  bill_version     INTEGER NOT NULL,
  rule_id          TEXT NOT NULL,
  amount_paise     BIGINT NOT NULL CHECK (amount_paise >= 0),
  line_fingerprint TEXT NOT NULL,
  reviewer_action_id TEXT NOT NULL,
  is_active        BOOLEAN NOT NULL DEFAULT true,
  PRIMARY KEY (tenant_id, override_id),
  FOREIGN KEY (tenant_id, claim_id) REFERENCES claim
);
CREATE UNIQUE INDEX one_active_override ON adjustment_override (tenant_id, claim_id, bill_version, line_no, rule_id) WHERE is_active;

